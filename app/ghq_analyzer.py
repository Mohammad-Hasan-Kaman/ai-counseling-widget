SUBSCALES = {
    'somatic': list(range(0,7)),
    'anxiety': list(range(7,14)),
    'social': list(range(14,21)),
    'depression': list(range(21,28))
}

def calculate_ghq_scores(answers):
    scores = {}
    for key, indices in SUBSCALES.items():
        scores[key] = sum(answers[i] for i in indices)
    scores['total'] = sum(answers)
    return scores

def interpret_score(score):
    if score <= 9:
        return 'سالم'
    elif score <= 15:
        return 'متوسط'
    else:
        return 'شدید'

def get_ghq_message(scores):
    msg = "📊 **نتایج تست سلامت عمومی شما:**\n"
    msg += f"- علائم جسمانی: {scores['somatic']} ({interpret_score(scores['somatic'])})\n"
    msg += f"- اضطراب و اختلال خواب: {scores['anxiety']} ({interpret_score(scores['anxiety'])})\n"
    msg += f"- اختلال عملکرد اجتماعی: {scores['social']} ({interpret_score(scores['social'])})\n"
    msg += f"- افسردگی شدید: {scores['depression']} ({interpret_score(scores['depression'])})\n"
    msg += f"- **نمره کلی: {scores['total']}**\n\n"
    if scores['total'] >= 43 or scores['depression'] >= 15:
        msg += "⚠️ وضعیت سلامت روان شما نیازمند توجه تخصصی است. پیشنهاد می‌کنیم در اسرع وقت نوبت مشاوره خود را ثبت فرمایید."
    elif scores['total'] >= 22:
        msg += "⚡ سلامت روان شما در برخی حوزه‌ها در معرض آسیب است. مشاوره می‌تواند کمک کننده باشد."
    else:
        msg += "✅ وضعیت سلامت عمومی شما مطلوب است."
    return msg